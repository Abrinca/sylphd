"""``--taxonomy tax`` parity with the real sylph-tax.

``tests/data/sylphtax/cases.json`` holds synthetic taxonomy sources and
``sylphd profile`` rows that cover every probe rule of ``sylph_to_taxprof.py``
(v1.9.2) — an empty key, truly empty lineage tokens, a key whose lineage comes
from a later source while its host survives from an earlier one, an
equal-abundance tie, repeated strain rows, an `ASM` path.  The goldens next to
it are the output of the real ``sylph_tax.sylph_to_taxprof.main`` (with and
without ``-a``) and ``merge_sylph_taxprof.merge_data`` on the same data,
regenerated by ``scripts/regen-sylphtax-golden.py``.

Two layers, as in the design note's parity plan:

* the golden tests resolve the hits with :meth:`MetadataDB.resolve`, fold them
  with :func:`aggregate_sylphtax_rows` and compare byte for byte with the
  committed goldens (profiles, the ``-a`` host column for the strain rows, and
  the matrix for all four values in the two-sample and one-sample form).  They
  always run, so CI without sylph-tax still guards format and resolution.
* the live tests rerun the real sylph-tax against a temporary copy of the
  sources and compare byte for byte, to catch drift in a newer sylph-tax.  They
  are skipped when ``sylph_tax`` is not importable (it needs pandas; the
  project venv does not install it).
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

import pytest

from sylphd.metadata import MetadataDB, TaxonomySource, build_metadata_db
from sylphd.taxonomy import (
    aggregate_samples,
    aggregate_sylphtax_rows,
    build_taxprof,
    clade_matrix_lines,
    hit_taxonomy_string,
    taxprof_lines,
)

DATA = Path(__file__).parent / "data" / "sylphtax"

#: ``sylph-tax merge --column`` for each ``--taxmatrix-value``.
SYLPH_TAX_COLUMNS = {
    "relative": "relative_abundance",
    "sequence": "sequence_abundance",
    "ani": "ANI",
    "coverage": "Coverage",
}


def load_cases() -> dict:
    return json.loads((DATA / "cases.json").read_text())


CASES = load_cases()
SOURCE_NAMES = [source["name"] for source in CASES["sources"]]


@pytest.fixture(scope="module")
def metadata(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """A metadata file with the synthetic sources, in the given order."""
    return _build_metadata(tmp_path_factory.mktemp("sylphtax-parity"))


def _source_text(rows: list[list[str | None]]) -> str:
    return "".join(
        f"{key}\t{lineage}\t{host}\n" if host is not None else f"{key}\t{lineage}\n"
        for key, lineage, host in rows
    )


def _build_metadata(directory: Path) -> Path:
    sources = []
    for index, source in enumerate(CASES["sources"]):
        path = directory / f"{index}-{source['name']}.tsv"
        path.write_text(_source_text(source["rows"]), newline="")
        sources.append(TaxonomySource(source["name"], path))
    output = directory / "meta.sqlite"
    build_metadata_db([], output, taxonomy=sources)
    return output


def rows_with_taxonomy(metadata: Path) -> list[dict]:
    """The cases' rows, with the ``tax_*`` values ``resolve`` gives them."""
    samples = []
    with MetadataDB(metadata) as db:
        for sample in CASES["samples"]:
            rows = [dict(row) for row in sample["rows"]]
            resolved = db.resolve(
                [(row["Genome_file"], row["Contig_name"]) for row in rows]
            )
            for row, taxonomy in zip(rows, resolved):
                row["Sample_file"] = sample["name"]
                row.update(taxonomy.columns())
            samples.append({"name": sample["name"], "rows": rows})
    return samples


def taxprof(samples: list[dict]) -> dict[str, str]:
    """Every sample's ``.sylphmpa`` text, as ``--taxonomy tax`` writes it."""
    written = {}
    for sample in samples:
        clades = aggregate_sylphtax_rows(sample["rows"])
        written[sample["name"]] = (
            "\n".join(
                taxprof_lines(
                    sample["name"],
                    "tax",
                    clades,
                    taxonomies_used=SOURCE_NAMES,
                )
            )
            + "\n"
        )
    return written


def resolved_hosts(samples: list[dict]) -> dict[str, str]:
    """The host sylph-tax's ``-a`` prints for every strain row of a sample.

    The key of a strain row is the last level of its path; an empty host token
    becomes ``UNKNOWN`` (and a row without a host is ``NA``), exactly as in
    ``sylph_to_taxprof``.  Later rows of the same clade win, like the dict
    assignment there.
    """
    hosts: dict[str, str] = {}
    for sample in samples:
        for row in sample["rows"]:
            clade = ""
            for token in hit_taxonomy_string(row).split(";"):
                token = token if token else "UNKNOWN"
                clade = token if not clade else f"{clade}|{token}"
            if not clade.rsplit("|", 1)[-1].startswith("t__"):
                continue
            host = row.get("tax_host")
            hosts[clade] = (
                "NA"
                if host is None
                else ";".join(token if token else "UNKNOWN" for token in host.split(";"))
            )
    return hosts


def annotated_hosts(text: str) -> dict[str, str]:
    """The strain-row hosts out of a ``sylph-tax taxprof -a`` profile."""
    hosts: dict[str, str] = {}
    for line in text.splitlines()[2:]:
        cells = line.split("\t")
        if len(cells) < 6:
            continue
        clade = cells[0]
        if clade.rsplit("|", 1)[-1].startswith("t__"):
            hosts[clade] = cells[5]
    return hosts


def matrix(samples: list[dict], value: str) -> str:
    table = aggregate_samples(samples, "tax")
    return "\n".join(clade_matrix_lines(table, value)) + "\n"


@pytest.fixture(scope="module")
def rows(metadata: Path) -> list[dict]:
    return rows_with_taxonomy(metadata)


@pytest.mark.parametrize("sample", [sample["name"] for sample in CASES["samples"]])
def test_golden(rows: list[dict], sample: str) -> None:
    """Byte-for-byte against what the real ``sylph-tax taxprof`` wrote."""
    produced = taxprof(rows)
    assert produced[sample] == (DATA / f"{sample}.sylphmpa").read_text()


@pytest.mark.parametrize("sample", [sample["name"] for sample in CASES["samples"]])
def test_server_taxprof_payload_matches_golden(rows: list[dict], sample: str) -> None:
    """The `/profile` `taxprof` helper (used by the server) is byte-identical too."""
    row_set = next(s for s in rows if s["name"] == sample)
    payload = build_taxprof(
        sample, ("tax",), row_set["rows"], tax_sources=SOURCE_NAMES
    )
    assert payload["tax"]["sylphmpa"] == (DATA / f"{sample}.sylphmpa").read_text()


def test_golden_annotated_hosts(rows: list[dict]) -> None:
    """The resolved hosts, against a real ``sylph-tax taxprof -a`` run.

    sylphd does not emit the sixth column yet, so only the hosts of the strain
    rows are compared; they are what phase 4 will print.
    """
    for sample in rows:
        expected = annotated_hosts(
            (DATA / f"{sample['name']}.annotated.sylphmpa").read_text()
        )
        produced = resolved_hosts([sample])
        assert produced == expected, sample["name"]
        # the fixture has both a real host and a host-less strain
        assert any(host not in {"NA"} for host in produced.values())
        assert "NA" in produced.values()


@pytest.mark.parametrize("value", list(SYLPH_TAX_COLUMNS))
@pytest.mark.parametrize("case", ["samples", "sample-a"])
def test_matrix_golden(rows: list[dict], value: str, case: str) -> None:
    """Byte-for-byte against ``sylph-tax merge --column`` on the same profiles.

    ``samples`` joins both profiles (pandas sorts the clade names);
    ``sample-a`` is the one-sample path, which keeps the profile order.
    """
    selected = rows if case == "samples" else rows[:1]
    produced = matrix(selected, value)
    assert produced == (DATA / f"{case}.matrix.{value}.tsv").read_text()


def _write_inputs(directory: Path) -> None:
    for source in CASES["sources"]:
        (directory / source["name"]).write_text(
            _source_text(source["rows"]), newline=""
        )
    header = "Sample_file\tGenome_file\tTaxonomic_abundance\tSequence_abundance"
    header += "\tAdjusted_ANI\tEff_cov\tContig_name"
    lines = [header]
    for sample in CASES["samples"]:
        for row in sample["rows"]:
            lines.append(
                "\t".join(
                    [
                        sample["name"],
                        row["Genome_file"],
                        repr(float(row["Taxonomic_abundance"])),
                        repr(float(row["Sequence_abundance"])),
                        repr(float(row["Adjusted_ANI"])),
                        repr(float(row["Eff_cov"])),
                        row["Contig_name"],
                    ]
                )
            )
    (directory / "rows.tsv").write_text("\n".join(lines) + "\n")


def _run_sylph_tax_live(
    directory: Path, *, annotate_hosts: bool = False, prefix: str = ""
) -> dict[str, str]:
    """Run the real ``sylph_tax.sylph_to_taxprof.main`` in ``directory``."""
    taxprof_main = pytest.importorskip(
        "sylph_tax.sylph_to_taxprof",
        reason="sylph-tax (and pandas) not installed",
    ).main
    _write_inputs(directory)
    previous = os.getcwd()
    os.chdir(directory)
    try:
        # The sources are passed by name, as sylphd names them, so the
        # Taxonomies_used line is comparable.
        taxprof_main(
            argparse.Namespace(
                taxonomy_dir=None,
                taxonomy_metadata=SOURCE_NAMES,
                sylph_results=["rows.tsv"],
                output_prefix=prefix,
                add_folder_information=False,
                overwrite=True,
                annotate_virus_hosts=annotate_hosts,
                pavian=False,
            ),
            None,
        )
    finally:
        os.chdir(previous)
    return {
        sample["name"]: (directory / f"{prefix}{sample['name']}.sylphmpa").read_text()
        for sample in CASES["samples"]
    }


def test_matches_sylph_tax_live(rows: list[dict], tmp_path: Path) -> None:
    """Live parity: the real sylph-tax on the same sources and rows."""
    live = _run_sylph_tax_live(tmp_path)
    assert taxprof(rows) == live
    annotated = _run_sylph_tax_live(
        tmp_path, annotate_hosts=True, prefix="annotated-"
    )
    for sample in rows:
        assert resolved_hosts([sample]) == annotated_hosts(
            annotated[sample["name"]]
        )


@pytest.mark.parametrize("value", list(SYLPH_TAX_COLUMNS))
def test_matches_sylph_tax_merge_live(rows: list[dict], tmp_path: Path, value: str) -> None:
    """``--taxmatrix`` for ``tax`` versus the real ``sylph-tax merge``."""
    merge_sylph_taxprof = pytest.importorskip(
        "sylph_tax.merge_sylph_taxprof",
        reason="sylph-tax (and pandas) not installed",
    )
    live = _run_sylph_tax_live(tmp_path)
    files = []
    for name, text in live.items():
        path = tmp_path / f"{name}.sylphmpa"
        path.write_text(text)
        files.append(path)
    expected = merge_sylph_taxprof.merge_data(
        files, SYLPH_TAX_COLUMNS[value]
    ).to_csv(sep="\t")
    assert matrix(rows, value) == expected
    one = merge_sylph_taxprof.merge_data(
        files[:1], SYLPH_TAX_COLUMNS[value]
    ).to_csv(sep="\t")
    assert matrix(rows[:1], value) == one
